// Refreshes the model price snapshot bundled with the Host from LiteLLM's public table.
// Run after `npm run build:typescript`: node tools/update-model-price-snapshot.mjs
import { writeFile } from "node:fs/promises";
import path from "node:path";

import {
  fetchLiteLlmPrices,
  modelPriceRecord,
  parseLiteLlmPrices,
} from "../packages/host-runtime/dist/local-usage-prices.js";

const output = path.resolve(
  import.meta.dirname,
  "../packages/host-runtime/src/local-usage-price-snapshot.ts",
);

const prices = parseLiteLlmPrices(await fetchLiteLlmPrices());
if (prices.size === 0) throw new Error("LiteLLM prices contain no priced models");
const record = modelPriceRecord(prices, Date.now());
const entries = Object.entries(record.prices)
  .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
  .map(([name, price]) => `    ${JSON.stringify(name)}: ${JSON.stringify(price)},`);
await writeFile(
  output,
  [
    "// Generated by tools/update-model-price-snapshot.mjs from LiteLLM's public price table.",
    "// Used only when neither the price cache nor LiteLLM is available. Do not edit by hand.",
    'import type { ModelPriceRecord } from "./local-usage-prices.js";',
    "",
    "export const LITELLM_PRICE_SNAPSHOT: ModelPriceRecord = {",
    "  formatVersion: 1,",
    `  fetchedAt: ${record.fetchedAt},`,
    "  prices: {",
    ...entries,
    "  },",
    "};",
    "",
  ].join("\n"),
);
process.stdout.write(
  `Wrote ${prices.size} model prices to ${path.relative(process.cwd(), output)}\n`,
);
